import {ApiError} from '../errors.js';
import {errors, noQuery, listQuery, resourceSchemas} from './schemas.js';

// Resource route files supply their module controller and deployed model metadata.
export function registerResourceRoutes(app, resource, controller) {
  const {base, one, list} = resourceSchemas(resource);
  app.get(resource.path, {
    schema: {...base, summary: `List ${resource.name}`, querystring: listQuery, response: {...errors, 200: list}},
  }, controller.list);
  app.get(resource.itemPath, {
    schema: {...base, summary: `Get ${resource.name}`, params: resource.keySchema, querystring: noQuery, response: {...errors, 200: one}},
  }, controller.get);
  if (!resource.readOnly) app.post(resource.path, {
    schema: {...base, summary: `Create ${resource.name}`, body: resource.createSchema, querystring: noQuery, response: {...errors, 201: one}},
  }, controller.create);
  if (resource.mode !== 'append') app.patch(resource.itemPath, {
    schema: {...base, summary: `Update ${resource.name}`, params: resource.keySchema, querystring: noQuery, body: resource.patchSchema, response: {...errors, 200: one}},
  }, controller.update);
  if (resource.mode === 'archive') app.delete(resource.itemPath, {
    schema: {...base, summary: `Archive ${resource.name}`, params: resource.keySchema, querystring: noQuery, response: {...errors, 204: {type: 'null'}}},
  }, controller.archive);

  const unsupported = ['PUT'];
  if (resource.mode === 'append') unsupported.push('PATCH');
  if (resource.mode !== 'archive') unsupported.push('DELETE');
  app.route({
    method: unsupported, url: resource.itemPath, schema: {hide: true},
    handler: async () => {
      throw new ApiError(405, 'OPERATION_NOT_ALLOWED', 'This resource does not support replacement, hard deletion or append-only mutation.');
    },
  });
  if (resource.readOnly) app.post(resource.path, {schema: {hide: true}}, async () => {
    throw new ApiError(405, 'OPERATION_NOT_ALLOWED', 'Audit events are generated by the API.');
  });
}
